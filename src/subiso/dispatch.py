"""Shipped dispatch policy: one regression tree over O(1) cheap features.

Each leaf ranks the engines by predicted mean log time ratio
``log(t_e / oracle)``; the portfolio tries them in that order and every
engine's own capability gating decides whether it can run.  The tree is
trained by ``scripts/lodo_train.py`` on the controlled grid plus the four TU
collections and by ``scripts/train_large.py`` on synthetic large hosts and HPRD
(one tree per protocol and host-size regime); the literals below are generated
-- regenerate them with the training scripts rather than editing by hand.
Features are O(1): nothing iterates over vertices or edges.
"""

