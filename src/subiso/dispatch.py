_FAST_PATH_ENV: bool = os.environ.get("SUBISO_FAST_PATH", "0").lower() in ("1", "true", "yes", "on")
_fast_path_enabled: bool | None = None


def is_fast_path_enabled() -> bool:
    """Return whether the O(1) fast-path router is active (default: False)."""
    if _fast_path_enabled is not None:
        return _fast_path_enabled
    return _FAST_PATH_ENV


def set_fast_path(enabled: bool | None) -> None:
    """Globally enable (True), disable (False), or reset to env var (None) the fast-path router."""
    global _fast_path_enabled
    _fast_path_enabled = enabled

