#: Largest host order in the small-tree training corpus (PROTEINS, n=620);
#: above this the policy switches to the large-host trees.
TRAINED_HOST_LIMIT = 620
#: Largest host order in the large-host training corpus (HPRD, 9,460).
LARGE_TRAINED_HOST_LIMIT = 9460


def host_stats(target: GraphLike) -> tuple[float, float, float]:
    """The host-side O(1) feature block ``(nodes, edges, density)``."""
    return node_count(target), edge_count(target), density(target)


def _counts(graph: GraphLike) -> tuple[int, int]:
    return node_count(graph), edge_count(graph)


def cheap_features(query: Query, *, host: tuple[float, float, float] | None = None) -> list[float]:
    """The O(1) feature vector used by the shipped rule."""
    nodes, edges, host_density = host if host is not None else host_stats(query.target)
    pattern_nodes, pattern_edges = _counts(query.pattern)
    pattern_density = 2 * pattern_edges / (pattern_nodes * (pattern_nodes - 1)) if pattern_nodes > 1 else 0.0
    return [
        nodes,
        edges,
        host_density,
        pattern_nodes,
        pattern_edges,
        pattern_density,
        pattern_density / (host_density if host_density > 1e-9 else 1e-9),
        pattern_nodes / (nodes if nodes > 1 else 1),
        1.0 if query.semantics is Semantics.INDUCED else 0.0,
        1.0 if query.node_attr is not None else 0.0,
    ]


@dataclass(frozen=True)
class _Split:
    """Internal node: route on ``features[feature] <= threshold``."""

    feature: int
    threshold: float
    below: _Node
    above: _Node


type _Node = _Split | tuple[str, ...]

