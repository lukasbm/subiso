def _leaf_order(features: list[float], prepared: bool, large: bool = False) -> tuple[str, ...]:
    if large:
        node: _Node = _RULE_LARGE_PREPARED if prepared else _RULE_LARGE_ONE_SHOT
    else:
        node = _RULE_PREPARED if prepared else _RULE_ONE_SHOT
    while isinstance(node, _Split):
        node = node.below if features[node.feature] <= node.threshold else node.above
    return node


class DispatchPolicy:
    """Rank all engines per query with the shipped regression tree or fast path."""

    def __init__(self, matchers: Sequence[Matcher], *, fast_path: bool | None = None) -> None:
        self._available = {matcher.name: matcher for matcher in matchers if matcher.available()}
        self._warned_large_host = False
        self._fast_path = fast_path

    def _is_fast_path(self) -> bool:
        if self._fast_path is not None:
            return self._fast_path
        return is_fast_path_enabled()

    def _order(self, query: Query, prepared: bool, host: tuple[float, float, float] | None) -> tuple[str, ...]:
        if self._is_fast_path():
            n_host = host[0] if host is not None else node_count(query.target)
            if n_host <= TRAINED_HOST_LIMIT:
                is_labelled = (query.node_attr is not None) or (query.edge_attr is not None)
                if is_labelled:
                    return ("glasgow", "vf2pp", "vf2", "fastiso", "lad")
                k = node_count(query.pattern)
                if k <= 4:
                    return ("vf2", "vf3l", "vf3p", "vf3", "vf2pp", "lad", "glasgow")
                return ("vf3l", "vf3p", "vf3", "vf2", "vf2pp", "lad", "glasgow")

        features = cheap_features(query, host=host)
        large = features[0] > TRAINED_HOST_LIMIT
        if features[0] > LARGE_TRAINED_HOST_LIMIT and not self._warned_large_host:
            warnings.warn(
                f"dispatch policy was trained on hosts up to {LARGE_TRAINED_HOST_LIMIT} vertices; "
                f"routing a host with {int(features[0])} vertices is extrapolation (see docs/writeup.pdf).",
                stacklevel=2,
            )
            self._warned_large_host = True
        return _leaf_order(features, prepared, large)

    def preferred(self, query: Query, *, prepared: bool = False, host: tuple[float, float, float] | None = None) -> str:
        """The rule's first choice; availability is decided in :meth:`candidates`."""
        return self._order(query, prepared, host)[0]

    def __call__(self, query: Query) -> Matcher:
        candidates = self.candidates(query)
        if not candidates:
            raise UnsupportedOperation("no available matcher")
        return candidates[0]

    def candidates(
        self, query: Query, *, prepared: bool = False, host: tuple[float, float, float] | None = None
    ) -> list[Matcher]:
        order = self._order(query, prepared, host)
        chosen = [self._available[name] for name in order if name in self._available]
        if chosen:
            return chosen
        return list(self._available.values())
